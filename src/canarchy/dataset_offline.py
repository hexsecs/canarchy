class OfflineDatasetProvider:
    """Synthetic datasets that need no network access.

    ``fetch`` generates data into the provider cache rather than recording a
    provenance stub, so the analysis commands downstream of it have real bytes to
    work with in an environment with no egress.
    """

    name = "offline"

    def _descriptors(self) -> list[DatasetDescriptor]:
        return [
            DatasetDescriptor(
                provider=self.name,
                name=dataset.name,
                version=dataset.version,
                source_url="https://github.com/hexsecs/canarchy",
                license=_SYNTHETIC_LICENSE,
                protocol_family=dataset.protocol_family,
                formats=(dataset.source_format,),
                size_description="< 1 MB (generated on demand)",
                description=f"SYNTHETIC: {dataset.summary}.",
                access_notes=_SYNTHETIC_NOTE,
                conversion_targets=("candump", "jsonl"),
                metadata={
                    "synthetic": True,
                    "generator": GENERATOR_VERSION,
                    "source_format": dataset.source_format,
                    "file_name": dataset.file_name,
                    "requires_network": False,
                },
            )
            for dataset in _DATASETS
        ]

    def _dataset(self, name: str) -> _OfflineDataset:
        for dataset in _DATASETS:
            if dataset.name == name:
                return dataset
        raise DatasetError(
            code="DATASET_NOT_FOUND",
            message=f"No dataset named '{name}' in the offline provider.",
            hint=(
                "Use `canarchy datasets search --provider offline` to list synthetic "
                "datasets that need no network access."
            ),
        )

    def search(self, query: str, limit: int = 20) -> list[DatasetDescriptor]:
        descriptors = self._descriptors()
        if not query.strip():
            return descriptors[:limit]
        needle = query.lower()
        # Deliberately not matched against `formats`: a source-format name like
        # `hcrl-csv` carries a research group's name, and a search for that
        # group should return their datasets, not a synthetic file that merely
        # shares the layout. Matching it would put synthetic data in the
        # results for exactly the query most likely to be looking for the real
        # thing. The format stays visible through `datasets inspect`.
        matched = [
            descriptor
            for descriptor in descriptors
            if needle in descriptor.name.lower()
            or needle in descriptor.description.lower()
            or needle in descriptor.protocol_family.lower()
        ]
        return matched[:limit]

    def inspect(self, name: str) -> DatasetDescriptor:
        dataset = self._dataset(name)
        for descriptor in self._descriptors():
            if descriptor.name == dataset.name:
                return descriptor
        raise DatasetError(  # pragma: no cover - descriptors mirror _DATASETS
            code="DATASET_NOT_FOUND",
            message=f"No dataset named '{name}' in the offline provider.",
        )

    def data_path(self, name: str) -> Path:
        """Return the cache path a generated dataset occupies.

        The generator and dataset versions are part of the path: a cached file
        from an older generator would otherwise be reused silently after the
        output changed, which would quietly invalidate any provenance hash
        recorded against it.
        """
        from canarchy.dataset_cache import provider_cache_dir

        dataset = self._dataset(name)
        return (
            provider_cache_dir(self.name)
            / "data"
            / f"v{GENERATOR_VERSION}"
            / f"{dataset.name}.v{dataset.version}.{dataset.file_name.rsplit('.', 1)[-1]}"
        )

    def fetch(self, name: str) -> DatasetResolution:
        """Generate the dataset into the cache and return its local path."""
        from canarchy.dataset_cache import now_utc_iso, save_provenance

        dataset = self._dataset(name)
        descriptor = self.inspect(name)
        path = self.data_path(name)
        is_cached = path.is_file() and path.stat().st_size > 0

        if not is_cached:
            # Publish atomically. A direct write that fails partway -- a full
            # cache filesystem is the realistic case -- would leave a non-empty
            # partial file, and the next fetch treats any non-empty path as
            # cached: it would record provenance for, and hand back, truncated
            # data. Write to a temporary sibling and rename only once the whole
            # dataset is on disk (#460 review).
            tmp_path: Path | None = None
            try:
                path.parent.mkdir(parents=True, exist_ok=True)
                with tempfile.NamedTemporaryFile(
                    mode="w",
                    encoding="utf-8",
                    dir=path.parent,
                    prefix=f".{path.name}.",
                    suffix=".partial",
                    delete=False,
                ) as handle:
                    tmp_path = Path(handle.name)
                    handle.write(dataset.generate(dataset.name))
                    handle.flush()
                    os.fsync(handle.fileno())
                os.replace(tmp_path, path)
                tmp_path = None
            except OSError as exc:
                raise DatasetError(
                    code="DATASET_GENERATION_FAILED",
                    message=f"Could not write generated dataset to {path}: {exc}",
                    hint="Check permissions and free space for the CANarchy cache directory.",
                    # A storage failure is a backend problem, not bad user
                    # input. The category is what the CLI maps to exit code 2,
                    # per this provider's error contract (#460 review).
                    category="backend",
                ) from exc
            finally:
                if tmp_path is not None:
                    # The publish never happened; do not leave the partial
                    # behind for a later fetch to trip over.
                    with contextlib.suppress(OSError):
                        tmp_path.unlink()

        provenance = {
            "provider": self.name,
            "dataset": name,
            "source_url": descriptor.source_url,
            "license": descriptor.license,
            "fetched_at": now_utc_iso(),
            "synthetic": True,
            "generator": GENERATOR_VERSION,
            "dataset_version": dataset.version,
            "source_format": dataset.source_format,
            "data_path": str(path),
            "note": _SYNTHETIC_NOTE,
        }
        save_provenance(self.name, name, provenance)
        return DatasetResolution(
            descriptor=descriptor,
            cache_path=path,
            is_cached=is_cached,
            provenance=provenance,
            data_materialized=True,
        )

    def refresh(self, name: str | None = None) -> list[DatasetDescriptor]:
        """Record a manifest summary; generated data is rebuilt on next fetch."""
        from canarchy.dataset_cache import now_utc_iso, save_manifest

        descriptors = self._descriptors()
        save_manifest(
            self.name,
            {
                "provider": self.name,
                "generated_at": now_utc_iso(),
                "generator": GENERATOR_VERSION,
                "dataset_count": len(descriptors),
                "datasets": [
                    {
                        "name": descriptor.name,
                        "protocol_family": descriptor.protocol_family,
                        "license": descriptor.license,
                        "synthetic": True,
                    }
                    for descriptor in descriptors
                ],
            },
        )
        return descriptors
